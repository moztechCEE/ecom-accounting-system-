const text = (value: unknown, max = 128): string => {
  if (typeof value !== 'string' || !value.trim() || value.length > max)
    throw new BadRequestException('檢測標準資料格式不符');
  return value;
};
const json = (value: unknown): Prisma.InputJsonValue =>
  JSON.parse(JSON.stringify(value)) as Prisma.InputJsonValue;
function calibrationDate(value: unknown): Date {
  const input = text(value, 40);
  if (
    !/^\d{4}-\d{2}-\d{2}T(?:[01]\d|2[0-3]):[0-5]\d:[0-5]\d(?:\.\d{1,3})?(?:Z|[+-]\d{2}:\d{2})$/.test(
      input,
    )
  )
    throw new BadRequestException('校正證明時間格式不符');
  const date = new Date(input),
    midnight = new Date(input.slice(0, 10) + 'T00:00:00Z');
  if (
    !Number.isFinite(date.getTime()) ||
    !Number.isFinite(midnight.getTime()) ||
    midnight.toISOString().slice(0, 10) !== input.slice(0, 10)
  )
    throw new BadRequestException('校正證明時間格式不符');
  return date;
}
