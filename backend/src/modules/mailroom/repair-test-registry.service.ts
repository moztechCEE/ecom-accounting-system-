// These two delegates are generated by the central schema owner, never by this module.
type RegistryDb = {
  repairTestStandard: Delegate<StandardRow>;
  repairCalibrationRecord: Delegate<CalibrationRow>;
  product: { findMany(args: Record<string, unknown>): Promise<ProductRow[]> };
  employee: {
    findFirst(args: Record<string, unknown>): Promise<{ id: string } | null>;
  };
  $executeRaw(sql: Prisma.Sql): Promise<number>;
};
