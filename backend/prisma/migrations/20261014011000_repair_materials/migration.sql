CREATE TABLE repair_material_allocations (
  id TEXT PRIMARY KEY,
  entity_id TEXT NOT NULL REFERENCES entities(id) ON DELETE RESTRICT,
  item_id TEXT NOT NULL REFERENCES mailroom_items(id) ON DELETE RESTRICT,
  inspection_revision INTEGER NOT NULL CHECK (inspection_revision > 0),
  plan_hash TEXT NOT NULL CHECK (plan_hash ~ '^[a-f0-9]{64}$'),
  requirement_id TEXT NOT NULL,
  product_id TEXT NOT NULL,
  warehouse_id TEXT NOT NULL REFERENCES warehouses(id) ON DELETE RESTRICT,
  required_quantity DECIMAL(18,2) NOT NULL,
  allocated_quantity DECIMAL(18,2) NOT NULL,
  received_quantity DECIMAL(18,2) NOT NULL DEFAULT 0,
  consumed_quantity DECIMAL(18,2) NOT NULL DEFAULT 0,
  released_quantity DECIMAL(18,2) NOT NULL DEFAULT 0,
  returned_quantity DECIMAL(18,2) NOT NULL DEFAULT 0,
  status TEXT NOT NULL DEFAULT 'ALLOCATED' CHECK (status IN ('ALLOCATED','RECEIVED','CONSUMED','RELEASED')),
  active_key TEXT UNIQUE,
  version INTEGER NOT NULL DEFAULT 1 CHECK (version > 0),
  allocated_by_id TEXT NOT NULL,
  allocated_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  physical_receipt_id TEXT UNIQUE,
  received_by_id TEXT,
  received_at TIMESTAMP(3),
  physical_return_id TEXT UNIQUE,
  returned_by_id TEXT,
  returned_at TIMESTAMP(3),
  return_location TEXT,
  consumed_by_id TEXT,
  consumed_at TIMESTAMP(3),
  released_by_id TEXT,
  released_at TIMESTAMP(3),
  reserve_transaction_id TEXT NOT NULL UNIQUE REFERENCES inventory_transactions(id) ON DELETE RESTRICT,
  out_transaction_id TEXT UNIQUE REFERENCES inventory_transactions(id) ON DELETE RESTRICT,
  release_transaction_id TEXT UNIQUE REFERENCES inventory_transactions(id) ON DELETE RESTRICT,
  cost_status TEXT NOT NULL DEFAULT 'UNKNOWN' CHECK (cost_status IN ('UNKNOWN','VERIFIED')),
  unit_cost DECIMAL(18,4),
  cost_currency TEXT,
  cost_source_reference TEXT,
  source_version TEXT,
  created_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (product_id, entity_id) REFERENCES products(id, entity_id) ON DELETE RESTRICT,
  CHECK (required_quantity > 0 AND required_quantity <= 100000 AND allocated_quantity = required_quantity),
  CHECK (received_quantity >= 0 AND received_quantity <= allocated_quantity),
  CHECK (consumed_quantity >= 0 AND consumed_quantity <= received_quantity),
  CHECK (returned_quantity >= 0 AND returned_quantity <= received_quantity - consumed_quantity),
  CHECK (received_quantity = 0 OR (physical_receipt_id IS NOT NULL AND received_by_id IS NOT NULL AND received_at IS NOT NULL)),
  CHECK (consumed_quantity = 0 OR (consumed_by_id IS NOT NULL AND consumed_at IS NOT NULL)),
  CHECK (returned_quantity = 0 OR (physical_return_id IS NOT NULL AND returned_by_id IS NOT NULL AND returned_at IS NOT NULL AND return_location IS NOT NULL AND length(trim(return_location)) > 0)),
  CHECK (released_quantity >= returned_quantity AND released_quantity <= allocated_quantity - consumed_quantity),
  CHECK (consumed_quantity = 0 OR out_transaction_id IS NOT NULL),
  CHECK (out_transaction_id IS NULL OR consumed_quantity > 0),
  CHECK (consumed_quantity = 0 OR active_key IS NOT NULL),
  CHECK (status <> 'RELEASED' OR consumed_quantity + released_quantity = allocated_quantity),
  CHECK (cost_status <> 'UNKNOWN' OR (unit_cost IS NULL AND cost_currency IS NULL AND cost_source_reference IS NULL)),
  CHECK (cost_status <> 'VERIFIED' OR (unit_cost IS NOT NULL AND unit_cost >= 0 AND cost_currency IS NOT NULL AND cost_currency ~ '^[A-Z]{3}$' AND cost_source_reference IS NOT NULL))
);
CREATE INDEX repair_material_allocations_context_idx ON repair_material_allocations(entity_id,item_id,inspection_revision,plan_hash);
CREATE INDEX repair_material_allocations_stock_idx ON repair_material_allocations(entity_id,status,product_id,warehouse_id);

CREATE TABLE repair_material_operations (
  id TEXT PRIMARY KEY,
  entity_id TEXT NOT NULL,
  item_id TEXT NOT NULL,
  allocation_id TEXT NOT NULL REFERENCES repair_material_allocations(id) ON DELETE RESTRICT,
  actor_id TEXT NOT NULL,
  request_id TEXT NOT NULL,
  request_hash TEXT NOT NULL CHECK (request_hash ~ '^[a-f0-9]{64}$'),
  action TEXT NOT NULL CHECK (action IN ('ALLOCATE','RECEIVE','CONSUME','RELEASE')),
  result JSONB NOT NULL,
  created_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE(entity_id,actor_id,request_id)
);
CREATE INDEX repair_material_operations_item_idx ON repair_material_operations(entity_id,item_id,created_at);
